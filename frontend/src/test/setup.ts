import "@testing-library/jest-dom";

Object.defineProperty(window, "matchMedia", {
  writable: true,
  value: (query: string) => ({
    matches: false,
    media: query,
    onchange: null,
    addListener: () => {},
    removeListener: () => {},
    addEventListener: () => {},
    removeEventListener: () => {},
    dispatchEvent: () => {},
  }),
});

// Node 25 ships an experimental global `localStorage` that shadows jsdom's and has no
// working methods without --localstorage-file. Install a plain in-memory Storage so the
// tests behave the same on every Node version.
class MemoryStorage implements Storage {
  private store = new Map<string, string>();
  get length() { return this.store.size; }
  clear() { this.store.clear(); }
  getItem(key: string) { return this.store.get(key) ?? null; }
  key(i: number) { return [...this.store.keys()][i] ?? null; }
  removeItem(key: string) { this.store.delete(key); }
  setItem(key: string, value: string) { this.store.set(key, String(value)); }
}
Object.defineProperty(window, "localStorage", { configurable: true, value: new MemoryStorage() });
Object.defineProperty(globalThis, "localStorage", { configurable: true, value: window.localStorage });
